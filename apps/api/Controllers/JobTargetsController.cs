using JobPilot.Api.Domain;
using JobPilot.Api.Infrastructure;
using JobPilot.Api.Services;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Http.Features;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.RateLimiting;

namespace JobPilot.Api.Controllers;

/// <summary>
/// Gerencia os alvos de vaga do usuário e organização via OCR de screenshots.
/// </summary>
[ApiController]
[Authorize]
[EnableRateLimiting(RateLimitPolicies.Analysis)]
[Route("api/job-targets")]
public sealed class JobTargetsController(
    JobTargetService targets,
    JobTargetSourceFileService files) : ControllerBase
{
    /// <summary>
    /// Lista os alvos de vaga do usuário.
    /// </summary>
    /// <returns>Lista de alvos de vaga.</returns>
    [HttpGet]
    public async Task<ActionResult<List<JobTargetDetail>>> List() =>
        Ok(await targets.ListAsync(User.UserId()));

    /// <summary>
    /// Retorna um alvo de vaga pelo identificador.
    /// </summary>
    /// <param name="id">Identificador do alvo.</param>
    /// <returns>Alvo encontrado ou 404.</returns>
    [HttpGet("{id:guid}")]
    public async Task<ActionResult<JobTargetDetail>> Get(Guid id)
    {
        var target = await targets.GetAsync(User.UserId(), id);
        return target is null ? NotFound() : Ok(target);
    }

    /// <summary>
    /// Organiza um novo alvo de vaga a partir dos dados fornecidos.
    /// </summary>
    /// <param name="request">Dados do alvo a ser organizado.</param>
    /// <returns>Alvo organizado.</returns>
    [HttpPost("organize")]
    public async Task<ActionResult<JobTargetDetail>> Organize(OrganizeJobTargetRequest request) =>
        Ok(await targets.OrganizeAsync(User.UserId(), request));

    /// <summary>
    /// Organiza um alvo de vaga a partir de uma screenshot enviada.
    /// </summary>
    /// <param name="file">Arquivo de imagem da screenshot.</param>
    /// <param name="useAi">Indica se deve utilizar IA para OCR.</param>
    /// <returns>Alvo organizado.</returns>
    [HttpPost("organize-screenshot")]
    [Consumes("multipart/form-data")]
    [RequestSizeLimit(10 * 1024 * 1024)]
    [RequestFormLimits(MultipartBodyLengthLimit = 10 * 1024 * 1024)]
    public async Task<ActionResult<JobTargetDetail>> OrganizeScreenshot(IFormFile file, [FromQuery] bool? useAi)
    {
        var saved = await files.SaveAsync(User.UserId(), file);
        // The path is generated by JobTargetSourceFileService and is checked again
        // inside JobTargetService before OCR. Never trust a path supplied by JSON.
        try
        {
            return Ok(await targets.OrganizeStoredImageAsync(User.UserId(), saved.Path, useAi ?? true));
        }
        finally
        {
            if (System.IO.File.Exists(saved.Path))
                System.IO.File.Delete(saved.Path);
        }
    }
}
